import * as fs from 'fs';
import path from 'path';
import {
    PerformanceMeasurement
} from '../truth-table-generator/calculate-bdd-quality.js';

export const BDD_TEMPLATE_LOCATION = path.join(
    __dirname,
    './bdd.template.ts'
);
export const BDD_OPTIMIZE_STATE_LOCATION = path.join(
    __dirname,
    './bdd.optimize.state.json'
);
export const BDD_TEMPLATE_GOAL = path.join(
    __dirname,
    './bdd.generated.ts'
);
export const RUST_BDD_GOAL = path.join(
    __dirname,
    '../../../rust/src/bdd_generated.rs'
);
export const DART_BDD_GOAL = path.join(
    __dirname,
    '../../../dart/lib/src/bdd_generated.dart'
);

export function writeBddTemplate(
    packedBddString: string,
    performanceMeasurement: PerformanceMeasurement,
    quality: number
) {
    let templateString: string = fs.readFileSync(BDD_TEMPLATE_LOCATION, 'utf-8');
    const replaceVariables = {
        packedBddString: '\'' + packedBddString + '\'',
    };

    Object.entries(replaceVariables).forEach(([key, content]) => {
        const contentString = content as string;
        const templateVar = '\'${' + key + '}\'';
        templateString = templateString.replace(templateVar, contentString);
    });

    fs.writeFileSync(
        BDD_OPTIMIZE_STATE_LOCATION,
        JSON.stringify({
            performanceMeasurement,
            packedBddString,
            quality
        }, null, 4),
        { encoding: 'utf8', flag: 'w' }
    );


    fs.writeFileSync(
        BDD_TEMPLATE_GOAL,
        templateString,
        { encoding: 'utf8', flag: 'w' }
    );

    fs.writeFileSync(
        RUST_BDD_GOAL,
        [
            '// This file is generated by the truth-table-generator of the JavaScript implementation.',
            '// Do not edit it by hand, run `npm run optimize-bdd` in ./javascript instead.',
            '',
            'pub const PACKED_BDD_STRING: &str = "' + packedBddString + '";',
            ''
        ].join('\n'),
        { encoding: 'utf8', flag: 'w' }
    );

    fs.writeFileSync(
        DART_BDD_GOAL,
        [
            '// This file is generated by the truth-table-generator of the JavaScript implementation.',
            '// Do not edit it by hand, run `npm run optimize-bdd` in ./javascript instead.',
            '',
            'const String packedBddString =',
            '    \'' + packedBddString + '\';',
            ''
        ].join('\n'),
        { encoding: 'utf8', flag: 'w' }
    );
}
