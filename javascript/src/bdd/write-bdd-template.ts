import * as fs from 'fs';
import path from 'path';
import { packedBddFromBase64String } from 'binary-decision-diagram';
import {
    PerformanceMeasurement
} from '../truth-table-generator/calculate-bdd-quality.js';

export const BDD_TEMPLATE_LOCATION = path.join(
    __dirname,
    './bdd.template.ts'
);
export const BDD_OPTIMIZE_STATE_LOCATION = path.join(
    __dirname,
    './bdd.optimize.state.json'
);
export const BDD_TEMPLATE_GOAL = path.join(
    __dirname,
    './bdd.generated.ts'
);
/**
 * The implementations in other languages only resolve the BDD that is created here.
 * They get the entries of the packed BDD as a native list of integers,
 * so they do not have to decode the packed BDD string.
 */
const OTHER_IMPLEMENTATIONS: {
    file: string;
    comment: string;
    lines: (entries: string) => string[];
}[] = [
    {
        file: 'rust/src/bdd_generated.rs',
        comment: '//',
        lines: entries => ['#[rustfmt::skip]', 'pub const PACKED_BDD: &[u16] = &[' + entries + '];']
    },
    {
        file: 'dart/lib/src/bdd_generated.dart',
        comment: '//',
        lines: entries => ['// dart format off', 'const List<int> packedBdd = [' + entries + '];']
    },
    {
        file: 'kotlin/src/main/kotlin/dev/rxdb/eventreduce/BddGenerated.kt',
        comment: '//',
        lines: entries => ['package dev.rxdb.eventreduce', '', 'public val PACKED_BDD: IntArray = intArrayOf(' + entries + ')']
    },
    {
        file: 'swift/Sources/RxDBEventReduce/BddGenerated.swift',
        comment: '//',
        lines: entries => ['// swift-format-ignore-file', 'public let packedBdd: [Int] = [' + entries + ']']
    },
    {
        file: 'csharp/src/RxDB.EventReduce/BddGenerated.cs',
        comment: '//',
        lines: entries => [
            'namespace RxDB.EventReduce',
            '{',
            '    /// <summary>The entries of the packed BDD that the JavaScript implementation created.</summary>',
            '    public static class BddGenerated',
            '    {',
            '        /// <summary>The entries of the packed BDD.</summary>',
            '        public static readonly int[] PackedBdd = { ' + entries + ' };',
            '    }',
            '}'
        ]
    },
    {
        file: 'python/src/rxdb_event_reduce/bdd_generated.py',
        comment: '#',
        lines: entries => ['PACKED_BDD: tuple[int, ...] = (' + entries + ')  # fmt: skip']
    },
    {
        file: 'go/bdd_generated.go',
        comment: '//',
        lines: entries => [
            'package eventreduce',
            '',
            '// PackedBdd has the entries of the packed BDD that the JavaScript implementation created.',
            'var PackedBdd = []int{' + entries + '}'
        ]
    }
];

/**
 * Writes the generated BDD files of the implementations in other languages.
 */
export function writeOtherImplementationBdds(packedBddString: string) {
    const entries = Array.from(packedBddFromBase64String(packedBddString));
    if (Math.max(...entries) > 0xFFFF) {
        throw new Error('the packed BDD does not fit into the 16 bit entries of the rust implementation');
    }
    OTHER_IMPLEMENTATIONS.forEach(({ file, comment, lines }) => {
        const content = [
            comment + ' Code generated by the truth-table-generator of the JavaScript implementation. DO NOT EDIT.',
            comment + ' Run `npm run optimize-bdd` in ./javascript instead.',
            '',
            ...lines(entries.join(', ')),
            ''
        ].join('\n');
        fs.writeFileSync(path.join(__dirname, '../../..', file), content, { encoding: 'utf8', flag: 'w' });
    });
}

export function writeBddTemplate(
    packedBddString: string,
    performanceMeasurement: PerformanceMeasurement,
    quality: number
) {
    let templateString: string = fs.readFileSync(BDD_TEMPLATE_LOCATION, 'utf-8');
    const replaceVariables = {
        packedBddString: '\'' + packedBddString + '\'',
    };

    Object.entries(replaceVariables).forEach(([key, content]) => {
        const contentString = content as string;
        const templateVar = '\'${' + key + '}\'';
        templateString = templateString.replace(templateVar, contentString);
    });

    fs.writeFileSync(
        BDD_OPTIMIZE_STATE_LOCATION,
        JSON.stringify({
            performanceMeasurement,
            packedBddString,
            quality
        }, null, 4),
        { encoding: 'utf8', flag: 'w' }
    );


    fs.writeFileSync(
        BDD_TEMPLATE_GOAL,
        templateString,
        { encoding: 'utf8', flag: 'w' }
    );

    writeOtherImplementationBdds(packedBddString);
}
